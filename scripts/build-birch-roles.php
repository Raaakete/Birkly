#!/usr/bin/env php
<?php
/**
 * Generate admin/css/birch/roles.generated.css from admin/css/birch/roles.json.
 *
 * The role decides how a thing looks (Birch Surfaces board): fill, line,
 * radius and shadow come only from here. Components add layout and type.
 *
 * Usage: php scripts/build-birch-roles.php [--check]
 */

$root = dirname(__DIR__);
$src = $root . '/admin/css/birch/roles.json';
$dst = $root . '/admin/css/birch/roles.generated.css';
$check = in_array('--check', $argv ?? [], true);

$looks = [
    'canvas' => ['background: none', 'border: 0', 'box-shadow: none'],
    'frame' => ['background: none', 'border: 1px solid var(--line)', 'border-radius: var(--r)', 'box-shadow: none', 'padding: var(--s-5)'],
    'slab' => ['background: var(--surface)', 'border: 0', 'border-radius: var(--r)', 'box-shadow: none'],
    'well' => ['background: var(--surface-2)', 'border: 0', 'border-radius: var(--r)', 'box-shadow: none'],
    'dashed' => ['background: none', 'border: 1px dashed var(--line-strong)', 'border-radius: var(--r)', 'box-shadow: none'],
    'signal' => ['background: var(--warning-soft)', 'border: 0', 'border-radius: var(--r)', 'box-shadow: none', 'color: var(--text)'],
    'float' => ['background: var(--bg)', 'border: 0', 'border-radius: var(--r)', 'box-shadow: var(--shadow-sheet)'],
    'menu' => ['background: var(--surface)', 'border: 0', 'border-radius: var(--r)', 'box-shadow: var(--shadow-menu)', 'padding: var(--s-1)'],
];

$fail = static function (string $msg): void {
    fwrite(STDERR, "roles.json: $msg\n");
    exit(1);
};

$map = json_decode((string) @file_get_contents($src), true);
if (!is_array($map) || !isset($map['entries']) || !is_array($map['entries'])) {
    $fail('missing or invalid');
}

$byRole = array_fill_keys(array_keys($looks), []);
$seen = [];
foreach ($map['entries'] as $i => $entry) {
    $sel = trim((string) ($entry['selector'] ?? ''));
    $role = (string) ($entry['role'] ?? '');
    if ($sel === '' || !isset($looks[$role])) {
        $fail("entry $i has no selector or an unknown role '$role'");
    }
    if (!preg_match('/^(\.[a-z][a-z0-9-]*)+$/', $sel)) {
        $fail("entry $i selector '$sel' must be plain classes only");
    }
    if (str_contains($sel, '.bk-')) {
        $fail("entry $i selector '$sel' uses a prefix");
    }
    if (isset($seen[$sel])) {
        $fail("'$sel' is assigned to both {$seen[$sel]} and $role");
    }
    $seen[$sel] = $role;
    $byRole[$role][] = $sel;
}

$list = static fn (array $sels): string => implode(",\n  ", $sels);
$scope = static fn (array $sels): string => ":where([data-birch]) :where(\n  " . implode(",\n  ", $sels) . "\n)";

$css = "/* Generated by scripts/build-birch-roles.php from roles.json — do not edit.\n"
    . "   Applies inside [data-birch] while pages migrate (P96); zero specificity. */\n";
foreach ($looks as $role => $decls) {
    if ($byRole[$role] === []) {
        continue;
    }
    sort($byRole[$role]);
    $css .= "\n/* $role */\n" . $scope($byRole[$role]) . " {\n  " . implode(";\n  ", $decls) . ";\n}\n";
}

$slabs = $byRole['slab'];
$frames = $byRole['frame'];
$signals = $byRole['signal'];
$css .= "\n/* Gaps, not borders: 4px between stacked slabs, 24px between frames */\n"
    . ":where([data-birch]) :where(\n  " . $list($slabs) . "\n) + :where(\n  " . $list($slabs) . "\n) {\n  margin-block-start: var(--s-1);\n}\n"
    . "\n:where([data-birch]) :where(\n  " . $list($frames) . "\n) + :where(\n  " . $list($frames) . "\n) {\n  margin-block-start: var(--s-6);\n}\n";
$css .= "\n/* Selected is a blue ring */\n" . $scope($slabs) . ":where(.is-selected, [aria-selected=\"true\"]) {\n  box-shadow: 0 0 0 2px var(--accent);\n}\n";
foreach (['danger', 'info', 'success'] as $tone) {
    $css .= "\n" . $scope($signals) . ":where(.is-$tone) {\n  background: var(--$tone-soft);\n}\n";
}

$current = is_file($dst) ? (string) file_get_contents($dst) : '';
if ($check) {
    if ($current !== $css) {
        fwrite(STDERR, "admin/css/birch/roles.generated.css is out of date (run php scripts/build-birch-roles.php)\n");
        exit(1);
    }
    echo 'Role CSS up to date (' . count($seen) . " selectors)\n";
    exit(0);
}
if ($current !== $css) {
    file_put_contents($dst, $css);
    echo 'Wrote admin/css/birch/roles.generated.css (' . count($seen) . " selectors)\n";
} else {
    echo 'No changes (' . count($seen) . " selectors)\n";
}
