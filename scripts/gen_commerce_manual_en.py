def flatten(obj, prefix=""):
    out = {}
    for k, v in obj.items():
        if k == "_meta":
            continue
        path = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(flatten(v, path))
        else:
            out[path] = str(v)
    return out

