    function resolve(name) {
        return Object.prototype.hasOwnProperty.call(ICON_ALIASES, name) ? ICON_ALIASES[name] : name;
    }

    /** 13 px, or 26 px (2 px per box) when 20 or more is asked for. */
    function pixelSize(requested) {
        const n = parseFloat(requested);
        return !isNaN(n) && n >= 20 ? 26 : 13;
    }

    /** Body path, then parts (data-part="a") and ghosts (data-part="1", hidden until a gesture). */
    function pixelPaths(entry) {
        if (typeof entry === 'string') {
            return '<path d="' + entry + '"/>';
        }
        // Integer-like keys enumerate first in JS; keep PHP's order (body, parts, ghosts).
        const layers = Object.keys(entry);
        const rank = function (k) { return k === '#' ? 0 : (/^[1-9]$/.test(k) ? 2 : 1); };
        layers.sort(function (a, b) { return rank(a) - rank(b) || (a < b ? -1 : a > b ? 1 : 0); });
        return layers.map(function (layer) {
            if (layer === '#') {
                return '<path d="' + entry[layer] + '"/>';
            }
            const ghost = /^[1-9]$/.test(layer) ? ' opacity="0"' : '';
            return '<path data-part="' + layer + '"' + ghost + ' d="' + entry[layer] + '"/>';
        }).join('');
    }

    /**
     * @param {string} name
     * @param {{size?: number|string, class?: string, title?: string, ariaHidden?: boolean, pixel?: boolean, gesture?: string|false}} [opts]
     *   gesture: override the hover gesture by name, or false for none.
     * @returns {string}
     */
    Birkly.icon = function icon(name, opts) {
        opts = opts || {};
        const birch = resolve(name);
        const usePixel = opts.pixel || !ICON_STROKE[birch];
        if (usePixel && !ICON_PIXEL[birch]) {
            return '';
        }

        const size = pixelSize(opts.size != null ? opts.size : 13);
        const extraClass = opts.class ? String(opts.class) : '';
        const className = ('birkly-icon' + (size === 26 ? ' birkly-icon--l' : '') + (extraClass ? ' ' + extraClass : '')).trim();
        const title = opts.title ? String(opts.title) : '';
        const ariaHidden = opts.ariaHidden != null ? opts.ariaHidden : !title;
        const gesture = opts.gesture !== undefined ? String(opts.gesture || '') : (ICON_GESTURES[birch] || '');
        const gestureAttr = /^[a-z][a-z0-9-]*$/.test(gesture) ? ' data-gesture="' + gesture + '"' : '';

        let titleMarkup = '';
        if (title) {
            const escaped = title.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
            titleMarkup = '<title>' + escaped + '</title>';
        }
        const ariaAttr = ariaHidden ? ' aria-hidden="true"' : '';
        const head = '<svg class="' + className + '" width="' + size + '" height="' + size + '" viewBox="0 0 13 13" ';

        if (usePixel) {
            return head + 'fill="currentColor" shape-rendering="crispEdges"' + gestureAttr + ariaAttr + '>' + titleMarkup + pixelPaths(ICON_PIXEL[birch]) + '</svg>';
        }
        return head + 'fill="none" stroke="currentColor" stroke-width="1" stroke-linecap="square"' + gestureAttr + ariaAttr + '>' + titleMarkup + '<path d="' + ICON_STROKE[birch] + '"/></svg>';
    };

    /**
     * Play the gesture of every icon in (or at) el once, e.g. the bell when a
     * notification arrives. No-op under prefers-reduced-motion (motion.css).
     * @param {Element|null} el
     */
    Birkly.iconPlay = function iconPlay(el) {
        if (!el) {
            return;
        }
        const icons = el.matches && el.matches('.birkly-icon[data-gesture]')
            ? [el]
            : Array.prototype.slice.call(el.querySelectorAll ? el.querySelectorAll('.birkly-icon[data-gesture]') : []);
        icons.forEach(function (svg) {
            svg.removeAttribute('data-play');
            void svg.getBoundingClientRect();
            svg.setAttribute('data-play', '');
            clearTimeout(svg.__birklyPlayTimer);
            svg.__birklyPlayTimer = setTimeout(function () {
                svg.removeAttribute('data-play');
            }, 2400);
        });
    };

    /**
     * @param {string} name
     * @param {{size?: number|string, class?: string, alt?: string, title?: string}} [opts]
     * @returns {string}
     */
    Birkly.iconImg = function iconImg(name, opts) {
        opts = opts || {};
        const alt = opts.alt != null ? String(opts.alt) : '';
        const extraClass = opts.class ? String(opts.class) : '';
        const className = ('birkly-icon-img' + (extraClass ? ' ' + extraClass : '')).trim();
        const sizeAttr = opts.size != null ? ' width="' + opts.size + '" height="' + opts.size + '"' : '';
        const titleAttr = opts.title ? ' title="' + String(opts.title).replace(/"/g, '&quot;') + '"' : '';
        const base = (typeof Birkly.url === 'function') ? Birkly.url('/admin/assets/icons/' + name + '.svg') : '/admin/assets/icons/' + name + '.svg';

        return '<img src="' + base + '" alt="' + alt.replace(/"/g, '&quot;') + '" class="' + className + '"' + sizeAttr + titleAttr + '>';
    };

    Birkly.iconNames = Object.keys(ICON_PIXEL).concat(Object.keys(ICON_STROKE).filter(function (n) { return !ICON_PIXEL[n]; }), Object.keys(ICON_ALIASES));
    Birkly.iconResolve = resolve;

    /**
     * Hydrate elements with data-icon="name" (optional data-icon-size, data-icon-class, data-icon-title,
     * data-icon-gesture: a gesture name, or "false" for none).
     * @param {ParentNode} [root]
     */
    Birkly.initIcons = function initIcons(root) {
        root = root || document;
        if (!root.querySelectorAll) {
            return;
        }

        root.querySelectorAll('[data-icon]').forEach(function (el) {
            if (el.getAttribute('data-icon-hydrated') === 'true') {
                return;
            }

            const name = el.getAttribute('data-icon');
            if (!name) {
                return;
            }

            const size = el.getAttribute('data-icon-size') || 13;
            const extraClass = el.getAttribute('data-icon-class') || '';
            const title = el.getAttribute('data-icon-title') || '';
            const ariaHiddenAttr = el.getAttribute('data-icon-aria-hidden');
            const ariaHidden = ariaHiddenAttr != null ? ariaHiddenAttr !== 'false' : !title;
            const gestureAttr = el.getAttribute('data-icon-gesture');
            const opts = {
                size: size,
                class: extraClass,
                title: title,
                ariaHidden: ariaHidden
            };
            if (gestureAttr != null) {
                opts.gesture = gestureAttr === 'false' ? false : gestureAttr;
            }
            const markup = Birkly.icon(name, opts);

            if (!markup) {
                return;
            }

            el.setAttribute('data-icon-hydrated', 'true');
            el.outerHTML = markup;
        });
    };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () {
            Birkly.initIcons();
        });
    } else {
        Birkly.initIcons();
    }
