<h3>Key Concepts</h3>
<p>Before diving in, here are the main concepts you'll work with in Birkly:</p>

<ul>
    <li><strong>Collections:</strong> Groups that organize your content (like "Blog Posts", "Products", "Team Members")</li>
    <li><strong>Entries:</strong> Individual pieces of content within a collection (like a single blog post or product)</li>
    <li><strong>Fields:</strong> The building blocks of your content (Title, Description, Image, etc.)</li>
    <li><strong>Media:</strong> Files like images, PDFs, or documents that you upload to use in your content</li>
</ul>

