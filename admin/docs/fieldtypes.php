<h2>Field Types</h2>
<p>Field types define what kind of information you can store in each field. Choosing the right field type is important for organizing your content effectively.</p>

<h3>Understanding Field Types</h3>
<p>Each field type is designed for a specific purpose. Here's a complete guide to all available field types:</p>

<h3>Text Fields</h3>
<div class="example-box">
    <h4>Text</h4>
    <p><strong>Use for:</strong> Short, single-line text</p>
    <p><strong>Examples:</strong> Titles, names, labels, short descriptions</p>
    <p><strong>Example values:</strong> "Welcome to Birkly", "John Doe", "Category: Technology"</p>
</div>

<div class="example-box">
    <h4>Textarea</h4>
    <p><strong>Use for:</strong> Longer text without formatting</p>
    <p><strong>Examples:</strong> Descriptions, summaries, plain text content</p>
    <p><strong>Example values:</strong> A paragraph describing your product, a plain text summary</p>
</div>

<div class="example-box">
    <h4>Editor</h4>
    <p><strong>Use for:</strong> Formatted text with styling options</p>
    <p><strong>Examples:</strong> Blog post content, articles, formatted descriptions</p>
    <p><strong>Features:</strong>
        <ul>
            <li>Bold, italic, underline text</li>
            <li>Headings (H1, H2, H3, etc.)</li>
            <li>Bullet and numbered lists</li>
            <li>Links</li>
            <li>Images</li>
            <li>And much more!</li>
        </ul>
    </p>
</div>

<h3>Media Fields</h3>
<div class="example-box">
    <h4>Media</h4>
    <p><strong>Use for:</strong> Single image or file</p>
    <p><strong>Examples:</strong> Featured images, profile pictures, document attachments</p>
    <p><strong>Supports:</strong> Images (JPG, PNG, GIF, SVG), PDFs, documents, videos</p>
</div>

<div class="example-box">
    <h4>Gallery</h4>
    <p><strong>Use for:</strong> Multiple images</p>
    <p><strong>Examples:</strong> Product galleries, portfolios, image carousels</p>
    <p><strong>Features:</strong> Upload multiple images, reorder them, add captions</p>
</div>

<h3>Data Fields</h3>
<div class="example-box">
    <h4>Number</h4>
    <p><strong>Use for:</strong> Numeric values</p>
    <p><strong>Examples:</strong> Prices, quantities, ratings, weights</p>
    <p><strong>Example values:</strong> 29.99, 100, 4.5</p>
</div>

<div class="example-box">
    <h4>Date</h4>
    <p><strong>Use for:</strong> Date selection</p>
    <p><strong>Examples:</strong> Publish dates, event dates, birthdays</p>
    <p><strong>Features:</strong> Calendar picker for easy date selection</p>
</div>

<div class="example-box">
    <h4>DateTime</h4>
    <p><strong>Use for:</strong> Date and time selection</p>
    <p><strong>Examples:</strong> Event start times, scheduled publication dates</p>
</div>

<h3>Selection Fields</h3>
<div class="example-box">
    <h4>Select</h4>
    <p><strong>Use for:</strong> Choosing from predefined options</p>
    <p><strong>Examples:</strong> Categories, status, size options</p>
    <p><strong>Example values:</strong> Status: "Draft", "Published", "Archived"</p>
</div>

<div class="example-box">
    <h4>Checkbox</h4>
    <p><strong>Use for:</strong> Yes/No or True/False options</p>
    <p><strong>Examples:</strong> "Published", "Featured", "In Stock", "Active"</p>
    <p><strong>Values:</strong> Checked = Yes/True, Unchecked = No/False</p>
</div>

<div class="example-box">
    <h4>Tags</h4>
    <p><strong>Use for:</strong> Multiple keywords or labels</p>
    <p><strong>Examples:</strong> Blog post tags, product categories, keywords</p>
    <p><strong>Features:</strong> Add multiple tags, separate with Enter key</p>
    <p><strong>Example values:</strong> ["technology", "tutorial", "cms"]</p>
</div>

<h3>Advanced Fields</h3>
<div class="example-box">
    <h4>Relation</h4>
    <p><strong>Use for:</strong> Linking entries from other collections</p>
    <p><strong>Examples:</strong> Linking blog posts to authors, products to categories</p>
    <p><strong>Use case:</strong> If you have a "Team" collection and a "Blog Posts" collection, you can relate blog posts to team members</p>
</div>

<div class="example-box">
    <h4>Dynamic Items</h4>
    <p><strong>Use for:</strong> Flexible, repeating content blocks</p>
    <p><strong>Examples:</strong> Flexible page builders, repeatable content sections</p>
    <p><strong>Advanced:</strong> This is a powerful field type for flexible content structures</p>
</div>

<h3>Choosing the Right Field Type</h3>
<p>Here's a quick guide:</p>
<ul>
    <li><strong>Need formatted text?</strong> → Use <strong>Editor</strong></li>
    <li><strong>Need plain long text?</strong> → Use <strong>Textarea</strong></li>
    <li><strong>Need short text?</strong> → Use <strong>Text</strong></li>
    <li><strong>Need to upload an image?</strong> → Use <strong>Media</strong></li>
    <li><strong>Need multiple images?</strong> → Use <strong>Gallery</strong></li>
    <li><strong>Need a date?</strong> → Use <strong>Date</strong></li>
    <li><strong>Need multiple keywords?</strong> → Use <strong>Tags</strong></li>
    <li><strong>Need to choose from options?</strong> → Use <strong>Select</strong></li>
    <li><strong>Need yes/no?</strong> → Use <strong>Checkbox</strong></li>
</ul>

<p>Now that you understand field types, you're ready to create well-organized collections!</p>

