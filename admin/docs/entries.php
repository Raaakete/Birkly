<h2>Entries</h2>
<p>Entries are the actual content pieces within your collections. Once you've created a collection, you can start adding entries to it.</p>

<h3>What is an Entry?</h3>
<p>An <strong>entry</strong> is a single piece of content that belongs to a collection. It's like filling out a form where each field you defined in the collection becomes an input.</p>

<div class="example-box">
    <h4>Example: Blog Entry</h4>
    <p>If your "Blog Posts" collection has these fields:</p>
    <ul>
        <li>Title</li>
        <li>Content</li>
        <li>Author</li>
        <li>Published Date</li>
    </ul>
    <p>Then each blog entry is one filled-out form with a title, content, author, and date.</p>
</div>

<h3>Creating an Entry</h3>
<p>To create a new entry:</p>
<ol>
    <li>Go to <strong>Content</strong> in the sidebar</li>
    <li>Click on the collection you want to add to (e.g., "Blog Posts")</li>
    <li>Click <strong>"New Entry"</strong> or <strong>"Add Entry"</strong></li>
    <li>Fill out all the fields:
        <ul>
            <li><strong>Title:</strong> Enter a descriptive title</li>
            <li><strong>Slug:</strong> This is automatically created from the title, or you can customize it (this becomes the URL)</li>
            <li><strong>Content:</strong> Write your content in the editor</li>
            <li><strong>Other fields:</strong> Fill in any other fields you defined</li>
        </ul>
    </li>
    <li>Set the <strong>Status:</strong>
        <ul>
            <li><strong>Draft:</strong> Save without publishing (not visible on website)</li>
            <li><strong>Published:</strong> Make it visible on your website</li>
        </ul>
    </li>
    <li>Click <strong>"Save"</strong> or <strong>"Save & Publish"</strong></li>
</ol>

<h3>Editing an Entry</h3>
<p>To edit an existing entry:</p>
<ol>
    <li>Go to the collection that contains the entry</li>
    <li>Find the entry in the list</li>
    <li>Click on the entry title or the edit button</li>
    <li>Make your changes</li>
    <li>Click <strong>"Save"</strong></li>
</ol>

<h3>Understanding Fields</h3>
<p>Each field type works a bit differently:</p>

<ul>
    <li><strong>Text Field:</strong> Simply type in the box</li>
    <li><strong>Textarea:</strong> A larger text box for longer content</li>
    <li><strong>Editor:</strong> A rich text editor with formatting tools:
        <ul>
            <li>Bold, Italic, Underline buttons</li>
            <li>Lists (bullet points, numbered)</li>
            <li>Headings</li>
            <li>Links</li>
            <li>And more!</li>
        </ul>
    </li>
    <li><strong>Media Field:</strong> Click to upload or select an image/file</li>
    <li><strong>Gallery:</strong> Upload multiple images</li>
    <li><strong>Date:</strong> Use the calendar picker to select a date</li>
    <li><strong>Tags:</strong> Type tags and press Enter after each one</li>
</li>
</ul>

<h3>Status and Publishing</h3>
<p>Every entry has a status:</p>

<ul>
    <li><strong>Draft:</strong> Your entry is saved but not visible on the website. Use this for work-in-progress content.</li>
    <li><strong>Published:</strong> Your entry is live and visible to visitors on your website.</li>
</ul>

<p>You can change the status at any time by editing the entry and selecting a different status.</p>

<h3>Slugs Explained</h3>
<p>A <strong>slug</strong> is the URL-friendly version of your entry's title. For example:</p>
<ul>
    <li>Title: "Getting Started with HaruCMS"</li>
    <li>Slug: "getting-started-with-harucms"</li>
</ul>

<p>The slug is used in the URL when someone views your entry. HaruCMS automatically creates slugs from titles, but you can customize them if needed.</p>

<h3>Tips for Managing Entries</h3>
<ul>
    <li><strong>Use drafts:</strong> Start entries as drafts and publish them when ready</li>
    <li><strong>Write meaningful titles:</strong> Clear titles help you find entries later</li>
    <li><strong>Use tags:</strong> Tags help organize and find related entries</li>
    <li><strong>Add excerpts:</strong> Summaries help when displaying entry lists</li>
    <li><strong>Set publish dates:</strong> Schedule content for future publication</li>
</ul>

