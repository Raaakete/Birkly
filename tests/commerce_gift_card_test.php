<?php
require_once __DIR__ . '/bootstrap.php';
test_reset_failures();
echo "Commerce gift card tests\n\n";
$root = dirname(__DIR__);
require_once $root . '/plugins/commerce/init.php';
$dataDir = sys_get_temp_dir() . '/birkly-gc-' . getmypid();
@mkdir($dataDir.'/orders',0755,true); @mkdir($dataDir.'/gift_cards',0755,true);
require_once $root . '/plugins/commerce/includes/GiftCardStore.php';
require_once $root . '/plugins/commerce/includes/DiscountEngine.php';
$giftCards = new GiftCardStore($dataDir.'/gift_cards');
$issued = $giftCards->issue(['balance_cents'=>3000,'code'=>'GC-TEST-1234']);
test_assert('G-01 issue', ($issued['balance_cents']??0)===3000);
$discounts = new DiscountEngine($dataDir);
$tender = $discounts->applyGiftCardTender(5000,'GC-TEST-1234',$giftCards);
test_assert('G-02 partial', ($tender['applied_cents']??0)===3000);
test_assert('G-04 void', true);
$giftCards->voidCard('GC-TEST-1234');
test_assert('G-04 rejected', ($giftCards->validateForRedeem('GC-TEST-1234')['ok']??true)===false);
exit(test_finish('commerce_gift_card_test'));
